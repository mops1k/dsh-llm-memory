export function t(locale, key, vars) {
  const dict = DICT[locale] ?? DICT.ru
  let value = dict[key] ?? DICT.en[key] ?? key
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement))
    }
  }
  return value
}

