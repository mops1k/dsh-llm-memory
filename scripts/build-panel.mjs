/**
 * Build the shared panel page for Kilo and OpenCode.
 *
 * The design lives as readable ES modules and CSS in `src/ui/design/panel/`
 * (the accepted `panel-ui-prototype`). Both hosts embed one self-contained file
 * (`src/ui/design/panel.html`), so the modules are bundled into one IIFE and the
 * stylesheets are inlined. The live transport is the compatibility JSON surface
 * of `src/adapters/panel/legacy-api.ts`; the host wires it through
 * `window.__LM_PANEL__` (see `src/adapters/panel/server.ts`).
 */
import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const designDir = fileURLToPath(new URL('../src/ui/design/panel/', import.meta.url))
const outfile = fileURLToPath(new URL('../src/ui/design/panel.html', import.meta.url))

const shell = readFileSync(`${designDir}index.html`, 'utf8')
const entry = `${designDir}js/main.js`

const bundle = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  minify: true,
  write: false,
  charset: 'utf8',
  legalComments: 'none',
  define: { __LM_EMBEDDED__: 'true' },
  logLevel: 'warning',
})

const js = bundle.outputFiles?.[0]?.text ?? ''
if (js.length === 0) throw new Error('build-panel: esbuild produced an empty bundle')

const css = ['styles/tokens.css', 'styles/app.css']
  .map(file => readFileSync(`${designDir}${file}`, 'utf8'))
  .join('\n')

function replaceOnce(source, needle, replacement, label) {
  if (!source.includes(needle)) throw new Error(`build-panel: shell is missing ${label}`)
  // A function replacement keeps `$&`/`$1` inside the bundle literal.
  return source.replace(needle, () => replacement)
}

let page = shell
const tokensLink = '<link rel="stylesheet" href="styles/tokens.css" />'
const appLink = '<link rel="stylesheet" href="styles/app.css" />'
if (!page.includes(tokensLink) || !page.includes(appLink)) {
  throw new Error('build-panel: shell is missing the stylesheet links')
}
page = page.replace(tokensLink, '').replace(appLink, () => `<style>${css}</style>`)
page = replaceOnce(page, '<script type="module" src="js/main.js"></script>', `<script>${js}</script>`, 'the module entry script')
page = replaceOnce(
  page,
  '<!doctype html>',
  '<!doctype html>\n<!-- Generated by scripts/build-panel.mjs from src/ui/design/panel/. Do not edit by hand. -->',
  'the doctype',
)

writeFileSync(outfile, page)
const size = (Buffer.byteLength(page) / 1024).toFixed(1)
console.log(`[llm-memory] panel page -> ${outfile} (${size} KiB, inlined CSS + JS)`)
