/**
 * Build helper: the shared panel design is authored for a standalone page
 * (`src/ui/design/panel/styles/*.css`). The dsh in-shell client keeps its own
 * tabbed chrome, so the prototype CSS is copied into the client bundle with
 * every selector scoped to `.lm-panel`. That keeps the exact prototype look
 * without leaking `.card`/`.btn`/`.table` rules into the dsh shell.
 *
 * The output is `client/panel-styles.js` (a classic script assigning
 * `__LM_PANEL_CSS__`), which `scripts/copy-client.mjs` prepends to
 * `client/client.js` when producing `lib/client.js`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

const SCOPE = '.lm-panel'

/** Read one CSS block body, respecting strings and nested braces. */
function readBlock(css, start) {
  let depth = 1
  let index = start
  let body = ''
  while (index < css.length && depth > 0) {
    const char = css[index]
    if (char === '"' || char === "'") {
      const quote = char
      body += char
      index++
      while (index < css.length) {
        const next = css[index]
        body += next
        index++
        if (next === '\\') {
          if (index < css.length) {
            body += css[index]
            index++
          }
          continue
        }
        if (next === quote) break
      }
      continue
    }
    if (char === '{') depth++
    if (char === '}') {
      depth--
      if (depth === 0) break
    }
    body += char
    index++
  }
  return { body, end: index + 1 }
}

function splitSelectors(selector) {
  const parts = []
  let current = ''
  let depth = 0
  for (const char of selector) {
    if (char === '(' || char === '[') depth++
    if (char === ')' || char === ']') depth--
    if (char === ',' && depth === 0) {
      parts.push(current)
      current = ''
      continue
    }
    current += char
  }
  parts.push(current)
  return parts
}

function prefixSelector(selector) {
  return splitSelectors(selector)
    .map(part => {
      const value = part.trim()
      if (!value) return ''
      if (value.startsWith(':root')) return SCOPE + value.slice(5)
      if (/^html(\b|$)/.test(value) || /^body(\b|$)/.test(value)) {
        return SCOPE + value.replace(/^(html|body)/, '')
      }
      return `${SCOPE} ${value}`
    })
    .filter(Boolean)
    .join(', ')
}

function prefixRules(css) {
  let output = ''
  let index = 0

  while (index < css.length) {
    const char = css[index]
    if (char === '/' && css[index + 1] === '*') {
      const end = css.indexOf('*/', index + 2)
      const stop = end === -1 ? css.length : end + 2
      output += css.slice(index, stop)
      index = stop
      continue
    }
    if (/\s/.test(char)) {
      output += char
      index++
      continue
    }
    if (char === '@') {
      let prelude = ''
      while (index < css.length && !'{;'.includes(css[index])) {
        prelude += css[index]
        index++
      }
      if (css[index] === ';') {
        output += `${prelude};`
        index++
        continue
      }
      const { body, end } = readBlock(css, index + 1)
      const name = prelude.trim().toLowerCase()
      const raw = /^@(?:-webkit-)?keyframes\b|^@font-face\b|^@page\b|^@property\b/.test(name)
      output += `${prelude}{${raw ? body : prefixRules(body)}}`
      index = end
      continue
    }

    let selector = ''
    while (index < css.length && css[index] !== '{' && css[index] !== '}') {
      selector += css[index]
      index++
    }
    if (css[index] !== '{') {
      output += selector
      index++
      continue
    }
    const { body, end } = readBlock(css, index + 1)
    output += `${prefixSelector(selector)}{${body}}`
    index = end
  }

  return output
}

export function scopedPanelCss() {
  const tokens = readFileSync(new URL('../src/ui/design/panel/styles/tokens.css', import.meta.url), 'utf8')
  const app = readFileSync(new URL('../src/ui/design/panel/styles/app.css', import.meta.url), 'utf8')
  return prefixRules(`${tokens}\n${app}`)
}

export function clientStylesSource() {
  return `/* Generated by scripts/build-client-css.mjs. Do not edit. */\nvar __LM_PANEL_CSS__ = ${JSON.stringify(scopedPanelCss())};\n`
}

function main() {
  const target = fileURLToPath(new URL('../client/panel-styles.js', import.meta.url))
  writeFileSync(target, clientStylesSource())
  console.log(`[dsh-llm-memory] client panel styles -> ${target}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main()
}
